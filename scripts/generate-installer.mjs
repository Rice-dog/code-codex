import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {verifyDomainCatalogs} from './localization-catalogs.mjs';
const root=resolve(import.meta.dirname,'..');
export function generateInstaller(write=false){
 verifyDomainCatalogs(false);
 const version=JSON.parse(readFileSync(resolve(root,'packages/explorer-ui/package.json'),'utf8')).version;
 const protocol=JSON.parse(readFileSync(resolve(root,'installer/worker-protocol.json'),'utf8'));assert.equal(protocol.schema,1);
 const assets=JSON.parse(readFileSync(resolve(root,protocol.managedAssets),'utf8'));assert.equal(assets.schema,1);
 for(const name of [...assets.generatedIcons,...assets.applicationEntries])assert(/^[A-Za-z][A-Za-z0-9._-]*$/.test(name),'Invalid managed asset name');
 assert.equal(new Set([...assets.generatedIcons,...assets.applicationEntries]).size,assets.generatedIcons.length+assets.applicationEntries.length,'Duplicate managed asset');
 const psArray=names=>'@('+names.map(name=>"'"+name+"'").join(',')+')';
 const managed='$GeneratedIconEntries = '+psArray(assets.generatedIcons)+'\n$ApplicationEntries = '+psArray(assets.applicationEntries)+' + $GeneratedIconEntries';
 const wix=readFileSync(resolve(root,'installer/Package.wxs'),'utf8');
 for(const icon of assets.generatedIcons)assert(new RegExp('<RemoveFile\\b[^>]*\\bName="'+icon.replaceAll('.','\\.')+'"[^>]*\\bOn="uninstall"','s').test(wix),'MSI managed icon cleanup drift: '+icon);
 const en=JSON.parse(readFileSync(resolve(root,'resources/i18n/en.json'),'utf8')),zh=JSON.parse(readFileSync(resolve(root,'resources/i18n/zh-CN.json'),'utf8'));
 const translations=Object.fromEntries(Object.keys(en).map(k=>[en[k].toLowerCase(),zh[k]]));
 const language="# language-resources:start\n# Generated from resources/i18n by scripts/check-i18n.mjs --write.\n$script:RemovalUiText = @'\n"+JSON.stringify(translations,null,2)+"\n'@ | ConvertFrom-Json\n# language-resources:end";
 const storage='# storage-contract:start\n'+readFileSync(resolve(root,'installer/Storage-Layout.ps1'),'utf8').trim()+'\n# storage-contract:end';
 const artifacts=[];
 for(const name of ['Install-CodeCodex','Uninstall-CodeCodex','Finalize-Uninstall']){
  let text='# Generated by scripts/generate-installer.mjs; edit installer/src and shared contracts.\n'+readFileSync(resolve(root,'installer/src/'+name+'.ps1.in'),'utf8');
  text=text.replace(/\{\{section:([a-z/-]+)\}\}/g,(_,section)=>{
   assert(protocol.sectionSources.includes(section),'Unknown worker section: '+section);
   return readFileSync(resolve(root,'installer/src/'+section+'.ps1'),'utf8');
  });
  text=text.replace('{{managed-assets}}',()=>managed);
  text=text.replaceAll('{{application-version}}',()=>version).replace('{{storage-contract}}',()=>storage).replace('{{language-resources}}',()=>language);
  text=text.replace(/\{\{common:([A-Za-z0-9-]+)\}\}/g,(_,name)=>{
   assert(protocol.commonSources.includes(name),'Unknown shared worker source: '+name);
   return readFileSync(resolve(root,'installer/src/common/'+name+'.ps1'),'utf8');
  });
  text=text.replaceAll('\r\n','\n').replace(/^\uFEFF/,'');
  assert(!/\{\{(?:common|section|managed|storage|language|application)[^}]*\}\}/.test(text),'Unresolved installer generator directive');
  const path=resolve(root,'installer/'+name+'.ps1'),priorBytes=readFileSync(path,'utf8'),prior=priorBytes.replace(/^\uFEFF/,'').replaceAll('\r\n','\n');
  const hash=value=>createHash('sha256').update(value).digest('hex');
  // Windows PowerShell 5.1 interprets a BOM-less -File script using the ANSI
  // code page. Generated workers contain Chinese UI resources and must retain
  // an explicit UTF-8 signature even when invoked directly from a ZIP.
  if(write)writeFileSync(path,'\uFEFF'+text);else {
   assert(priorBytes.startsWith('\uFEFF'),'Generated worker requires UTF-8 BOM for WinPS 5.1: '+name);
   assert.equal(hash(prior),hash(text),'Generated worker drift: '+name+'. Update installer/src and regenerate.');
  }
  const required=name==='Uninstall-CodeCodex'?protocol.uninstallParameters:name==='Finalize-Uninstall'?protocol.finalizerParameters:[];
  const params=text.slice(0,text.indexOf('# storage-contract:')>0?text.indexOf('# storage-contract:'):text.indexOf('# language-resources:'));
  for(const key of required)assert(new RegExp('\\$'+key+'\\b').test(params),'Missing worker protocol parameter: '+name+'/'+key);
  artifacts.push(name+'.ps1');
 }
 return artifacts;
}
if(process.argv[1]===import.meta.filename)console.log('Standalone installer workers verified: '+generateInstaller(process.argv.includes('--write')).join(', '));
